"""운영시간 원문 해석(VISIT-1 TODAY). 원문은 운영 DB `libraries.operating_time_text` 실제 표기(2026-11-25)."""

import pytest

from app.services.hours import week_hours

WD = "월화수목금토일"


def fmt(raw: str) -> str:
    return " ".join(f"{WD[d]}{h}" for d, h in sorted(week_hours(raw).items()))


WEEK_18_17 = "월09:00~18:00 화09:00~18:00 수09:00~18:00 목09:00~18:00 금09:00~18:00 토09:00~17:00 일09:00~17:00"


@pytest.mark.parametrize("raw, expected", [
    # 쉼표로 나눈 평일·주말(운영 167곳, 광주 대부분) — 기존 파서는 못 읽었다
    ("평일 09:00~18:00, 주말 09:00~17:00", WEEK_18_17),
    ("평일 09:00~18:00, 주말 09:00~17:00 (점심시간 휴무)", WEEK_18_17),
    ("평일: 09:00~18:00, 주말: 09:00~17:00", WEEK_18_17),
    ("(평일) 09:00~18:00 (주말) 09:00~17:00", WEEK_18_17),
    ("9:00~18:00 (평일) 9:00~17:00(주말)", WEEK_18_17),
    ("평일 : 오전9시~오후6시 / 주말 : 오전9시~오후5시", WEEK_18_17),
    ("평일 9시~18시, 주말 9시~17시", WEEK_18_17),
    ("평일 09:00~22:00 / 주말 09:00~17:00",
     "월09:00~22:00 화09:00~22:00 수09:00~22:00 목09:00~22:00 금09:00~22:00 토09:00~17:00 일09:00~17:00"),
    ("월 ~ 금요일 : 09:00~22:00, 토요일 : 09:00~18:00",
     "월09:00~22:00 화09:00~22:00 수09:00~22:00 목09:00~22:00 금09:00~22:00 토09:00~18:00"),
    ("월요일-목요일 09:00-21:00 / 토-일요일 09:00-17:00",
     "월09:00~21:00 화09:00~21:00 수09:00~21:00 목09:00~21:00 토09:00~17:00 일09:00~17:00"),
    ("평일(화~금) 09:00~22:00, 주말(토,일) 09:00~18:00",
     "화09:00~22:00 수09:00~22:00 목09:00~22:00 금09:00~22:00 토09:00~18:00 일09:00~18:00"),
    ("평일&middot;주말 09:00~18:00", " ".join(f"{d}09:00~18:00" for d in WD)),
    ("평일,주말 09:00~18:00", " ".join(f"{d}09:00~18:00" for d in WD)),
    ("매주 화~토요일 09:00~18:00", " ".join(f"{d}09:00~18:00" for d in "화수목금토")),
    # 요일 없는 시간 하나 = 나머지 요일 전부(휴관은 closed_text가 정함)
    ("09:00 ~ 18:00", " ".join(f"{d}09:00~18:00" for d in WD)),
    ("종합자료실 09:00~20:00(토,일 09:00~17:00)",
     "월09:00~20:00 화09:00~20:00 수09:00~20:00 목09:00~20:00 금09:00~20:00 토09:00~17:00 일09:00~17:00"),
    ("09:00~18:00, 매주 수요일 09:00~21:00",
     "월09:00~18:00 화09:00~18:00 수09:00~21:00 목09:00~18:00 금09:00~18:00 토09:00~18:00 일09:00~18:00"),
    # 여러 실: 책을 빌리는 자료실 기준, 열람·학습실 시간은 쓰지 않는다
    ("자료실: 평일 09:00~18:00, 주말 09:00~17:00 / 학습실 07:00~22:00(법정공휴일: 09:00~18:00)", WEEK_18_17),
    ("자료실 09:00~18:00 / 열람실 07:00~22:00", " ".join(f"{d}09:00~18:00" for d in WD)),
    ("(주중) 열람실 08:00~23:00  자료실 09:00~22:00 (주말) 열람실 08:00~23:00 자료실 09:00~18:00",
     "월09:00~22:00 화09:00~22:00 수09:00~22:00 목09:00~22:00 금09:00~22:00 토09:00~18:00 일09:00~18:00"),
    ("[평일] 문헌정보실09:00~20:00, 어린이실,디지털실 09:00~18:00 [주말] 09:00~17:00",
     "월09:00~20:00 화09:00~20:00 수09:00~20:00 목09:00~20:00 금09:00~20:00 토09:00~17:00 일09:00~17:00"),
    ("어린이 자료실: 평일 9시~20시,토&middot;일 9시~18시 / 일반자료실: 평일 9시~22시,토&middot;일 9시~18시 / 열람실: 8시~22시",
     "월09:00~22:00 화09:00~22:00 수09:00~22:00 목09:00~22:00 금09:00~22:00 토09:00~18:00 일09:00~18:00"),
    # 점심시간은 운영시간이 아니다
    ("화~금요일 10:00~18:00, 토요일 10:00~17:00 / 12:00~13:00 (점심시간) 이용불가",
     "화10:00~18:00 수10:00~18:00 목10:00~18:00 금10:00~18:00 토10:00~17:00"),
    ("월~금요일 운영 09:00~18:00 (점심시간 휴무 13:00~14:00)", " ".join(f"{d}09:00~18:00" for d in "월화수목금")),
    # 모르면 비운다(앱은 "운영시간 미확인")
    ("예약자만 09:00~18:00", ""),
    ("하절기 07:00~22:00, 동절기 08:00~22:00", ""),
    ("3월~10월(하절기): 7:00 - 22:00 / 11월~2월(동절기): 8:00 - 22:00", ""),
    ("점심시간 미운영 : 12:30 ~ 13:30", ""),
    ("-", ""),
    ("홈페이지 운영시간 안내 참고", ""),
    ("매일 29:00~99:99", ""),
])
def test_week_hours(raw, expected):
    assert fmt(raw) == expected


def test_week_hours_empty():
    assert week_hours(None) == {} and week_hours("") == {}
